GROUP BY `month`
ORDER BY `total amounts in determined month` DESC
LIMIT 0, 1;


# 4.10 Prepare a report showing: month → number of rentals → revenue.
SHOW FULL TABLES;
SELECT * FROM payment;
SELECT * FROM rental;

SELECT
	YEAR(rental.rental_date) AS `year`,
	MONTHNAME(rental.rental_date) AS `month`,
    COUNT(rental.rental_id) AS `number of rentals`,
	SUM(payment.amount) AS `total amounts in determined month` 
FROM payment
JOIN rental
	ON payment.rental_id = rental.rental_id
GROUP BY `year`, `month`;


