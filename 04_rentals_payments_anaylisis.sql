# 4.2 Determine which customer made the highest number of rentals.
SHOW FULL TABLES;
SELECT * FROM rental;

# how many rentals has each customer:
SELECT
	rental.customer_id,
	COUNT(rental_id) AS `number of rentals`
FROM rental
GROUP BY rental.customer_id;

# Solution using MAX, COUNT and VIEW:
CREATE VIEW rentals_per_customer AS
SELECT
	customer_id,
	COUNT(rental_id) AS 
    `number of rentals`
FROM rental
GROUP BY customer_id;

SELECT
    customer_id,
    `number of rentals`
FROM rentals_per_customer
WHERE `number of rentals` = (
    SELECT MAX(`number of rentals`)
    FROM rentals_per_customer);

