# 4.5 Calculate the revenue generated by each store.
SHOW FULL TABLES;
SELECT * FROM payment;
SELECT * FROM staff;
SELECT * FROM store;
SELECT * FROM address;

SELECT
	address.address AS `address of store`,
    SUM(amount) AS `revenue generated by each store`
FROM payment
JOIN staff
	ON payment.staff_id = staff.staff_id
JOIN store
	ON staff.store_id = store.store_id
JOIN address
	ON store.address_id = address.address_id
GROUP BY payment.staff_id;


# 4.6 Determine which staff member processed the highest total payment amount.
SHOW FULL TABLES;
SELECT * FROM payment;
SELECT * FROM staff;

# Solution using ORDER BY and LIMIT:
SELECT
	CONCAT(staff.first_name, ' ', staff.last_name) AS `staff`,
	SUM(payment.amount) AS `total payment amount`
FROM payment
JOIN staff
	ON payment.staff_id = staff.staff_id
GROUP BY payment.staff_id
ORDER BY `total payment amount` DESC
LIMIT 0, 1;

# Solution using SUM(), MAX() and VIEW:
CREATE OR REPLACE VIEW total_payment_amount_processed_by_staff AS
SELECT
	CONCAT(staff.first_name, ' ', staff.last_name) AS `staff`,
	SUM(payment.amount) AS `total payment amount`
FROM payment
JOIN staff
	ON payment.staff_id = staff.staff_id
GROUP BY staff.first_name, staff.last_name;

DROP VIEW IF EXISTS total_payment_amount_processed_by_staff;

SELECT
	`staff`,
    `total payment amount`
FROM total_payment_amount_processed_by_staff
WHERE `total payment amount` =
	(SELECT
		MAX(`total payment amount`)
	FROM total_payment_amount_processed_by_staff);


# 4.7 Find the most frequently rented films.
SHOW FULL TABLES;
SELECT * FROM film;
SELECT * FROM inventory;
SELECT * FROM rental;

# Solution using ORDER BY and LIMIT:
SELECT
	film.title,
    COUNT(rental.rental_id) AS `number of rentals`
FROM film
JOIN inventory
	ON film.film_id = inventory.film_id
JOIN rental
	ON inventory.inventory_id = rental.inventory_id
GROUP BY film.film_id
ORDER BY `number of rentals` DESC
LIMIT 0 ,1;

# Solution using COUNT(), MAX() and VIEW:
CREATE OR REPLACE VIEW rentals_per_film AS
SELECT
	film.film_id,
    film.title,
    COUNT(rental.rental_id) AS `number of rentals`
FROM film
JOIN inventory
	ON film.film_id = inventory.film_id
JOIN rental
	ON inventory.inventory_id = rental.inventory_id
    GROUP BY film.film_id, film.title;

SELECT
	film_id,
    title,
    `number of rentals`
FROM rentals_per_film
WHERE `number of rentals` =
	(SELECT
		MAX(`number of rentals`)
	FROM rentals_per_film);


# 4.8 Find films that have never been rented.
SHOW FULL TABLES;
SELECT * FROM film;
SELECT * FROM inventory;
SELECT * FROM rental;

SELECT
    film.title,
    COUNT(rental.rental_id) AS `number of rentals`
FROM film
LEFT JOIN inventory
	ON film.film_id = inventory.film_id
LEFT JOIN rental
	ON inventory.inventory_id = rental.inventory_id
GROUP BY film.film_id
HAVING `number of rentals` = 0;

# How many films have never been rented:
CREATE OR REPLACE VIEW films_never_rented AS
SELECT
    film.title,
    COUNT(rental.rental_id) AS `number of rentals`
FROM film
LEFT JOIN inventory
	ON film.film_id = inventory.film_id
LEFT JOIN rental
	ON inventory.inventory_id = rental.inventory_id
GROUP BY film.film_id
HAVING `number of rentals` = 0;

DROP VIEW IF EXISTS film_never_rented;

SELECT
	COUNT(`number of rentals`) AS `number of films never rented`
FROM films_never_rented;


# 4.9 Determine the month with the highest revenue.
SHOW FULL TABLES;
